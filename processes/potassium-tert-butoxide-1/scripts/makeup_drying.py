"""Balance of the make-up tert-butanol's dehydration (A-001, DESIGN.md D-004), a specified split.

The make-up arrives as the tert-butanol/water azeotrope (11.76 wt% water, US 5 053 560 A) and is
dried past it in a vapour-phase molecular-sieve (3A) unit: evaporated and superheated on LP
steam, the water adsorbed, the dry vapour condensed on cooling water; the off-line bed is
regenerated by an electrically heated nitrogen loop, whose condenser takes the desorbed water.
Core has no adsorption model (an adsorber is only checked), so the split and the duties come
from here, every value ASSUMED (D-004, D-009) except where its source is named.

Reads the two feeds (S3 tert-butanol contained, S4 the azeotrope's water) from
process/flowsheet.yaml and writes the dried make-up S6, the regeneration condensate S7 and the
unit's energy streams Q10, Q11, Q12 and P4 in the flowsheet's units (kg/h, kW). Run it with
`cheme run scripts/makeup_drying.py` in the process folder; with BALANCE_OUTPUT set it writes
the balance-output contract (library ADR 0027).
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]

M_TBA, M_H2O = 74.123, 18.015            # kg/kmol (IUPAC 2021)
T_IN, T_BUB, T_SUP, T_OUT = 308.15, 353.15, 393.15, 308.15   # K
# property values (DESIGN.md SRC-9): liquid cp at the mean of 308-353 K (thermo's
# ZABRANSKY_SPLINE_C at 330.65 K: 246.4; water 75.4, CoolProp's IAPWS water); heats of
# vaporization at 353 K (tert-butanol 39.07 kJ/mol at 355.5 K, Majer and Svoboda via the NIST
# WebBook; water 41.58 kJ/mol at 353.15 K, CoolProp's IAPWS water); ideal-gas cp at the mean of
# 353-393 K (thermo's TRCIG: tert-butanol 135.5, water 34.0 kJ/(kmol K))
CP_L = {"TBA": 246.4, "H2O": 75.4}
DH_VAP = {"TBA": 39070.0, "H2O": 41580.0}
CP_G = {"TBA": 135.5, "H2O": 34.0}
# ASSUMED (D-004): the dried make-up's water, the tert-butanol lost to the regeneration
# condensate (co-adsorbed and in the bed's voids), the heat of adsorption of water on a 3A sieve
# (about 65 kJ/mol, an order of magnitude; no measured value read) and the regeneration heat as
# 1.5 times it (the desorption and the bed's and the nitrogen's heating), the nitrogen blower
W_DRY = 0.001            # mass fraction of water in the dried make-up
TBA_LOSS = 0.01          # share of the make-up's tert-butanol in the regeneration condensate
DH_ADS = 3600.0          # kJ per kg of water adsorbed
REGEN_FACTOR = 1.5       # regeneration heat / heat of adsorption
BLOWER_KW = 1.0          # the regeneration loop's blower, year average


def feeds():
    doc = yaml.safe_load((ROOT / "process" / "flowsheet.yaml").read_text(encoding="utf-8"))
    flows = {s["id"]: s["state"]["design"]["flow"]["value"] for s in doc["streams"] if s["id"] in ("S3", "S4")}
    return flows["S3"], flows["S4"]


def balance():
    tba_in, water_in = feeds()
    tba_dry = tba_in * (1.0 - TBA_LOSS)
    water_dry = tba_dry * W_DRY / (1.0 - W_DRY)
    tba_regen = tba_in - tba_dry
    water_regen = water_in - water_dry
    kmol = {"TBA": tba_in / M_TBA, "H2O": water_in / M_H2O}
    # evaporator: the azeotrope heated to its bubble point, vaporised and superheated (kJ/h)
    q_evap = sum(n * (CP_L[c] * (T_BUB - T_IN) + DH_VAP[c] + CP_G[c] * (T_SUP - T_BUB)) for c, n in kmol.items())
    # product condenser: the dry vapour desuperheated, condensed and cooled to 308 K, with the
    # heat of adsorption the vapour carries out of the bed
    dry = {"TBA": tba_dry / M_TBA, "H2O": water_dry / M_H2O}
    q_ads = DH_ADS * (water_regen)
    q_cond = sum(n * (CP_G[c] * (T_SUP - T_BUB) + DH_VAP[c] + CP_L[c] * (T_BUB - T_OUT)) for c, n in dry.items()) + q_ads
    # regeneration: heat in, and the loop's condenser takes the rest (the unit's energy closure)
    q_regen = REGEN_FACTOR * q_ads
    q_regen_cond = q_evap + q_regen - q_cond
    total_regen = tba_regen + water_regen
    return {
        "S6": {"flow": round(tba_dry + water_dry, 4), "temperature": T_OUT,
               "composition": {"TBA": round(tba_dry / (tba_dry + water_dry), 6), "H2O": round(water_dry / (tba_dry + water_dry), 6)}},
        "S7": {"flow": round(total_regen, 4),
               "composition": {"TBA": round(tba_regen / total_regen, 6), "H2O": round(water_regen / total_regen, 6)}},
        "Q10": {"duty": round(q_evap / 3600.0, 4)},
        "Q11": {"duty": round(q_cond / 3600.0, 4)},
        "Q12": {"duty": round(q_regen_cond / 3600.0, 4)},
        "P4": {"duty": round(q_regen / 3600.0 + BLOWER_KW, 4)},
    }


def write_balance_output(cases):
    """With BALANCE_OUTPUT set, write the values the flowsheet cites from this script as JSON.

    The process library's balance-output contract (docs/adr/0027 of the library): case ->
    stream id -> quantity, in the flowsheet's units and basis. The library's
    scripts/check_balance_scripts.py re-runs this script and compares them with
    process/flowsheet.yaml.
    """
    import json
    import os

    target = os.environ.get("BALANCE_OUTPUT")
    if target:
        doc = {"contract": "balance-output/1", "script": f"scripts/{Path(__file__).name}",
               "cases": cases}
        Path(target).write_text(json.dumps(doc, indent=1, default=float), encoding="utf-8")


def main():
    values = balance()
    for key, val in values.items():
        print(key, val)
    write_balance_output({"design": values})


if __name__ == "__main__":
    main()
